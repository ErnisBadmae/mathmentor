"""Пререквизиты тем как фиксированные данные (как фазы в ``program.py``).

Ключи и значения — названия тем (``TopicORM.title``), так же как темы адресуются в
``_requires_manual_review_path``. Это не граф альтернативных маршрутов и не оптимизатор:
плоская карта «тему C не даём, пока не закрыты A и B». Порядок внутри фазы по-прежнему
задаёт ``program_order``; эта карта добавляет только жёсткие ворота по мастерству.

Держим её маленькой и defensible: рёбра только внутри авто-дрилла Части 1, где зависимость
педагогически очевидна. Часть 2 / manual-review темы в авто-дрилл и так не попадают.
"""

from __future__ import annotations

PREREQUISITES: dict[str, tuple[str, ...]] = {
    "Применение производной: экстремумы": ("Производная: геометрический смысл",),
    "Простейшие уравнения (показательные, логарифмические)": (
        "Вычисления: логарифмы и тригонометрия",
    ),
    "Уравнения и неравенства с ОДЗ": ("Простейшие уравнения (показательные, логарифмические)",),
    "Неравенства": ("Простейшие уравнения (показательные, логарифмические)",),
}


def prerequisites_met(
    topic_title: str,
    passed_titles: set[str],
    prerequisites: dict[str, tuple[str, ...]],
) -> bool:
    """True, если у темы нет пререквизитов или все они уже закрыты (есть PASSED-evidence).

    Чистая функция: ``passed_titles`` — темы с ``solved_count > 0``, ``prerequisites`` —
    карта (передаётся явно, чтобы тесты не зависели от глобала)."""
    return all(prereq in passed_titles for prereq in prerequisites.get(topic_title, ()))
